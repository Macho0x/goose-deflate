#!/usr/bin/env python3
"""Regenerate tests/vectors.goose from Python zlib and gzip.

Raw DEFLATE is zlib.compressobj(wbits=-15). The zlib wrapper is
zlib.compress. gzip is gzip.compress with mtime 0. mixed() in
tests/self_check.goose must use the same bytes as mixed() here.
"""

import gzip
import pathlib
import sys
import zlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "tests" / "vectors.goose"


def mixed(n=4096):
    text = b"Goose deflate block.\n"
    out = bytearray()
    for i in range(n):
        if i < 256:
            out.append(text[i % len(text)])
        elif i < 768:
            out.append(0)
        else:
            out.append((i * 17 + (i >> 3)) & 0xFF)
    return bytes(out)


def raw_compress(data):
    comp = zlib.compressobj(level=6, wbits=-15)
    return comp.compress(data) + comp.flush()


def first_block_type(data):
    acc = 0
    n = 0
    at = 0

    def get(k):
        nonlocal acc, n, at
        while n < k:
            if at >= len(data):
                raise SystemExit("truncated while reading a block header")
            acc |= data[at] << n
            at += 1
            n += 8
        v = acc & ((1 << k) - 1)
        acc >>= k
        n -= k
        return v

    get(1)
    return get(2)


def goose_const(name, data):
    lines = ["const %s: u8[%d] = [" % (name, len(data))]
    for i in range(0, len(data), 16):
        chunk = ", ".join("0x%02x" % b for b in data[i : i + 16])
        lines.append("    %s," % chunk)
    lines.append("];")
    return "\n".join(lines)


def main():
    samples = {
        "EMPTY": b"",
        "SHORT": b"goose",
        "REPEAT": b"a" * 100,
        "MIXED": mixed(),
    }
    raw = {k: raw_compress(v) for k, v in samples.items()}
    wrapped = {k: zlib.compress(v) for k, v in samples.items()}
    gz = {k: gzip.compress(v, mtime=0) for k, v in samples.items()}

    for key, data in samples.items():
        if zlib.decompress(raw[key], wbits=-15) != data:
            raise SystemExit("raw roundtrip failed for " + key)
        if zlib.decompress(wrapped[key]) != data:
            raise SystemExit("zlib roundtrip failed for " + key)
        if gzip.decompress(gz[key]) != data:
            raise SystemExit("gzip roundtrip failed for " + key)

    expect = {"EMPTY": 1, "SHORT": 1, "REPEAT": 1, "MIXED": 2}
    for key, btype in expect.items():
        got = first_block_type(raw[key])
        if got != btype:
            raise SystemExit("%s block type %s, wanted %s" % (key, got, btype))

    parts = [
        "// Generated by goldens.py. Do not edit by hand.",
        "// Raw streams are zlib.compressobj(level=6, wbits=-15).",
        "// ZLIB_* is zlib.compress. GZIP_* is gzip.compress(mtime=0).",
        "// MIXED is the 4096-byte buffer built by mixed() in self_check.goose.",
        "",
        "namespace vectors;",
        "",
    ]
    blobs = []
    for key in ("EMPTY", "SHORT", "REPEAT", "MIXED"):
        blobs.append(("RAW_" + key, raw[key]))
        blobs.append(("ZLIB_" + key, wrapped[key]))
        blobs.append(("GZIP_" + key, gz[key]))
    for name, data in blobs:
        parts.append(goose_const(name, data))
        parts.append("")
    OUT.write_text("\n".join(parts) + "\n")
    print("wrote %s" % OUT)
    for name, data in blobs:
        print("%s %d" % (name, len(data)))


if __name__ == "__main__":
    sys.exit(main())
